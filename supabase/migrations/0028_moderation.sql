-- Undo tricks: accents, leetspeak (0 1 3 4 5 7 $ @ ! | €), separators, repeated letters ("porrrco", "p.o.r.c.o", "p0rc0").
create or replace function public.mod_prep(p text) returns text language sql immutable as $$
  select translate(lower(coalesce(p, '')), 'àáâäãåèéêëìíîïòóôöõùúûüçñ013457$@!|€', 'aaaaaaeeeeiiiiooooouuuucnoieastsaiie');
$$;

-- Returns the word that matched, or null if the text is clean.
create or replace function public.mod_check(p text) returns text language plpgsql stable security definer set search_path = public as $$
declare
  raw text := lower(coalesce(p, '')); pre text := public.mod_prep(p);
  comp text := regexp_replace(pre, '[^a-z]', '', 'g'); compc text;
  toks text[] := array(select t from regexp_split_to_table(pre, '[^a-z]+') t where t <> ''); tokc text[];
  r record; a record;
begin
  for a in select term from public.moderation_allow loop comp := replace(comp, a.term, ''); end loop;
  compc := regexp_replace(comp, '(.)\1+', '\1', 'g');
  tokc := array(select regexp_replace(t, '(.)\1+', '\1', 'g') from unnest(toks) t);
  for r in select word, word_c, mode from public.moderation_words loop
    if r.mode = 'sub' then
      if comp like '%' || r.word || '%' or compc like '%' || r.word_c || '%' then return r.word; end if;
    elsif r.mode = 'word' then
      if r.word = any(toks) or r.word_c = any(tokc) or r.word = comp or r.word_c = compc then return r.word; end if;
    else
      if raw like '%' || r.word || '%' then return r.word; end if;
    end if;
  end loop;
  return null;
end $$;
revoke execute on function public.mod_check(text), public.mod_prep(text) from public, anon, authenticated;

-- Pre-check used by sign-up and the nickname sheet. A blocked attempt is logged (at most 60 an hour in total) for the admin.
create or replace function public.nickname_check(p_name text) returns text
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := trim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g')); hit text;
begin
  if char_length(n) < 2 or char_length(n) > 24 or n !~ '^[[:alnum:]_ .-]+$' then return 'bad_nickname'; end if;
  hit := public.mod_check(n);
  if hit is not null then
    if (select count(*) from public.moderation_log where created_at > now() - interval '1 hour') < 60
       and not exists (select 1 from public.moderation_log where text = n and created_at > now() - interval '1 day') then
      insert into public.moderation_log (user_id, text, matched, source) values (auth.uid(), left(n, 40), hit, 'nickname');
    end if;
    return 'nickname_not_allowed';
  end if;
  if exists (select 1 from public.profiles where lower(display_name) = lower(n)) then return 'nickname_taken'; end if;
  return 'ok';
end $$;
grant execute on function public.nickname_check(text) to anon, authenticated;

create or replace function public.set_nickname(p_name text) returns text
language plpgsql security definer set search_path = public as $$
declare n text := trim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  if not public.is_registered() then raise exception 'registration_required'; end if;
  if char_length(n) < 2 or char_length(n) > 24 or n !~ '^[[:alnum:]_ .-]+$' then raise exception 'bad_nickname'; end if;
  if public.mod_check(n) is not null then raise exception 'nickname_not_allowed'; end if;
  begin
    update public.profiles set display_name = n where id = auth.uid();
  exception when unique_violation then raise exception 'nickname_taken';
  end;
  return n;
end $$;
grant execute on function public.set_nickname(text) to authenticated;

-- Friend-group names are public too.
create or replace function public.create_group(p_name text) returns text
language plpgsql security definer set search_path = public as $$
declare
  c text; nm text := trim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
  alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; hit text;
begin
  if not public.is_registered() then raise exception 'registration_required'; end if;
  if char_length(nm) < 2 or char_length(nm) > 30 or nm ~ '[<>]' then raise exception 'bad_nickname'; end if;
  hit := public.mod_check(nm);
  if hit is not null then
    insert into public.moderation_log (user_id, text, matched, source) values (auth.uid(), left(nm, 40), hit, 'group');
    raise exception 'nickname_not_allowed';
  end if;
  loop
    c := (select string_agg(substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1), '') from generate_series(1, 6));
    exit when not exists (select 1 from public.groups where code = c);
  end loop;
  insert into public.groups (code, name, owner) values (c, nm, auth.uid());
  insert into public.group_members (group_code, user_id) values (c, auth.uid());
  return c;
end $$;
grant execute on function public.create_group(text) to authenticated;

-- The "guard": names that were fine yesterday may not be today (the list grows). Offenders lose their name and the admin hears about it.
create or replace function public.scan_names() returns integer
language plpgsql security definer set search_path = public as $$
declare r record; hit text; n integer := 0;
begin
  for r in select id, display_name from public.profiles where display_name is not null loop
    hit := public.mod_check(r.display_name);
    if hit is not null then
      insert into public.moderation_log (user_id, text, matched, source) values (r.id, left(r.display_name, 40), hit, 'existing');
      update public.profiles set display_name = null where id = r.id;
      n := n + 1;
    end if;
  end loop;
  for r in select code, name from public.groups loop
    hit := public.mod_check(r.name);
    if hit is not null then
      insert into public.moderation_log (user_id, text, matched, source) values (null, left(r.name, 40), hit, 'group');
      update public.groups set name = 'Gruppo ' || r.code where code = r.code;
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
