#!/usr/bin/env python3
"""Builds web/src/lib/italyMap.ts: simplified outlines of the Italian provinces (grouped by region) for the map picker.
Source: Natural Earth 1:10m admin-1 (public domain), https://github.com/nvkelso/natural-earth-vector (geojson/ne_10m_admin_1_states_provinces.geojson).
Usage: python3 scripts/build-italy-map.py path/to/ne_10m_admin_1_states_provinces.geojson > web/src/lib/italyMap.ts"""
import json, math, sys

K = 100.0                       # units per degree of latitude
X0, Y0 = 6.5, 47.2              # lon / lat of the top-left corner
CX = math.cos(math.radians(42.5))
EPS = 0.9                       # simplification tolerance, in units (about 1 km)
REGION_NAME = {"Apulia": "Puglia", "Sicily": "Sicilia", "Valle d'Aosta": "Valle d'Aosta"}
EN = {"Puglia": "Apulia", "Sicilia": "Sicily", "Piemonte": "Piedmont", "Lombardia": "Lombardy", "Toscana": "Tuscany", "Sardegna": "Sardinia", "Valle d'Aosta": "Aosta Valley"}
# the capital of each province, as people say it (the data has the province name)
CAPITAL = {"Turin": "Torino", "Aoste": "Aosta", "Crotene": "Crotone", "Bozen": "Bolzano", "Forlì-Cesena": "Forlì", "Pesaro e Urbino": "Pesaro", "Reggio Emilia": "Reggio Emilia",
  "Barletta-Andria Trani": "Barletta", "Verbano-Cusio-Ossola": "Verbania", "Carbonia-Iglesias": "Carbonia", "Olbia-Tempio": "Olbia", "Medio Campidano": "Sanluri",
  "Ogliastra": "Lanusei", "Oristrano": "Oristano", "Massa-Carrara": "Massa", "Monza e Brianza": "Monza", "Genova": "Genova", "L'Aquila": "L'Aquila"}

def slug(s): return "".join(c if c.isalnum() else "-" for c in s.lower()).strip("-")
def proj(lon, lat): return ((lon - X0) * CX * K, (Y0 - lat) * K)

def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    idx, dmax = 0, 0.0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / n
        if d > dmax: idx, dmax = i, d
    if dmax <= eps: return [pts[0], pts[-1]]
    return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)

def ring_path(ring):
    pts = [proj(lon, lat) for lon, lat in ring]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    if max(xs) - min(xs) < 2.5 and max(ys) - min(ys) < 2.5: return None      # specks
    # a ring starts and ends on the same point: split it at the point farthest from the start and simplify the two halves
    k = max(range(1, len(pts) - 1), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
    s = rdp(pts[: k + 1], EPS)[:-1] + rdp(pts[k:], EPS)
    if len(s) < 4: return None
    out, px, py = [], 0, 0
    for i, (x, y) in enumerate(s[:-1]):
        xi, yi = round(x), round(y)
        out.append(("M%d %d" % (xi, yi)) if i == 0 else ("l%d %d" % (xi - px, yi - py)))
        px, py = xi, yi
    return "".join(out) + "z"

d = json.load(open(sys.argv[1]))
feats = [f for f in d["features"] if f["properties"].get("iso_a2") == "IT"]
regions = {}
provs = []
for f in feats:
    p = f["properties"]
    reg = REGION_NAME.get(p["region"], p["region"])
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    paths = []
    for poly in polys:
        for ring in poly[:1]:
            r = ring_path(ring)
            if r: paths.append(r)
    name = CAPITAL.get(p["name"], p.get("woe_name") or p["name"])
    if p["name"] == "Genova": name = "Genova"
    x, y = proj(p["longitude"], p["latitude"])
    provs.append({"id": slug(p["name"]), "region": slug(reg), "name": name, "d": "".join(paths), "x": round(x), "y": round(y), "lat": round(p["latitude"], 4), "lon": round(p["longitude"], 4)})
    r = regions.setdefault(slug(reg), {"id": slug(reg), "name": reg, "en": EN.get(reg, reg), "xs": [], "ys": []})
    for path in paths:
        pass
    r["xs"].append(x); r["ys"].append(y)

# bounding boxes from the drawn points
def bbox_of(path):
    import re
    x = y = 0; xs = []; ys = []
    for m in re.finditer(r"([Mlz])(-?\d+)?[ ]?(-?\d+)?", path):
        c, a, b = m.groups()
        if c == "z" or a is None: continue
        if c == "M": x, y = int(a), int(b)
        else: x += int(a); y += int(b)
        xs.append(x); ys.append(y)
    return xs, ys
for r in regions.values():
    xs, ys = [], []
    for pv in provs:
        if pv["region"] == r["id"]:
            a, b = bbox_of(pv["d"]); xs += a; ys += b
    r["box"] = [min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)]
    r["cx"] = round(sum(r["xs"]) / len(r["xs"])); r["cy"] = round(sum(r["ys"]) / len(r["ys"]))
    del r["xs"], r["ys"]
allx, ally = [], []
for pv in provs:
    a, b = bbox_of(pv["d"]); allx += a; ally += b
box = [min(allx), min(ally), max(allx) - min(allx), max(ally) - min(ally)]
print("// Generated by scripts/build-italy-map.py from Natural Earth (public domain, https://www.naturalearthdata.com). Do not edit by hand.")
print("export interface MapRegion { id: string; name: string; en: string; box: [number, number, number, number]; cx: number; cy: number }")
print("export interface MapProvince { id: string; region: string; name: string; d: string; x: number; y: number; lat: number; lon: number }")
print("export const ITALY_BOX: [number, number, number, number] = %s;" % json.dumps(box))
print("export const MAP_REGIONS: MapRegion[] = %s;" % json.dumps(sorted(regions.values(), key=lambda r: r["name"]), ensure_ascii=False, separators=(",", ":")))
print("export const MAP_PROVINCES: MapProvince[] = %s;" % json.dumps(provs, ensure_ascii=False, separators=(",", ":")))
